// The pg dependency is loaded only when DB_CLIENT=postgres. Previous SQLite
// tests and local npm start work without any running PostgreSQL server.
const SEED_ITEMS = [
  'Підготувати практичну №1',
  'Налаштувати Git та GitHub',
  'Продемонструвати GET /items',
  'Підготуватися до Google Meet'
];

export async function openPostgresDatabase({ poolFactory } = {}) {
  const { default: pg } = poolFactory ? { default: null } : await import('pg');
  const Pool = poolFactory || pg.Pool;
  const pool = new Pool({
    host: process.env.DB_HOST || 'localhost',
    port: Number(process.env.DB_PORT || 5432),
    user: process.env.DB_USER || 'taskflow',
    password: process.env.DB_PASSWORD,
    database: process.env.DB_NAME || 'taskflow',
    max: 10,
    connectionTimeoutMillis: 5000
  });

  try {
    // Docker Compose waits for pg_isready; bounded retries also support manual starts.
    for (let attempt = 1; attempt <= 10; attempt++) {
      try { await pool.query('SELECT 1'); break; }
      catch (error) {
        if (attempt === 10) throw error;
        await new Promise(resolve => setTimeout(resolve, 1500));
      }
    }
    await pool.query(`
      CREATE TABLE IF NOT EXISTS items (
        id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
        name TEXT NOT NULL CHECK(length(trim(name)) > 0)
      );
      CREATE TABLE IF NOT EXISTS tasks (
        id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
        title TEXT NOT NULL CHECK(length(trim(title)) BETWEEN 1 AND 120),
        status TEXT NOT NULL DEFAULT 'open' CHECK(status IN ('open', 'done')),
        owner_id INTEGER NOT NULL DEFAULT 1,
        category_id INTEGER,
        created_at TEXT NOT NULL,
        updated_at TEXT NOT NULL
      );
      CREATE TABLE IF NOT EXISTS idempotency_keys (
        key TEXT PRIMARY KEY,
        payload_hash TEXT NOT NULL,
        response_json TEXT NOT NULL,
        created_at TEXT NOT NULL
      );
    `);
    // Only seed when empty, preserving student changes on container restart.
    const count = await pool.query('SELECT COUNT(*)::integer AS total FROM items');
    if (count.rows[0].total === 0) {
      for (const name of SEED_ITEMS) {
        await pool.query('INSERT INTO items(name) VALUES ($1)', [name]);
      }
    }
    return { kind: 'postgres', pool, close: () => pool.end() };
  } catch (error) {
    await pool.end();
    throw error;
  }
}
